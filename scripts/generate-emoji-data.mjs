import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = process.argv[2] ? path.resolve(process.argv[2]) : null;
const outputFile = process.argv[3]
  ? path.resolve(process.argv[3])
  : path.join(projectRoot, 'emoji-data.js');

if (!sourceDir) {
  console.error('Usage: node scripts/generate-emoji-data.mjs <emoji-directory> [output-file]');
  process.exit(1);
}

const categoryEntries = await readdir(sourceDir, { withFileTypes: true });
const categories = {};
const seen = new Set();

for (const categoryEntry of categoryEntries.sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
  if (!categoryEntry.isDirectory() || categoryEntry.name.startsWith('.')) continue;

  const files = await readdir(path.join(sourceDir, categoryEntry.name), { withFileTypes: true });
  const shortcodes = files
    .filter((entry) => entry.isFile() && path.extname(entry.name).toLowerCase() === '.png')
    .map((entry) => path.basename(entry.name, path.extname(entry.name)))
    .sort((a, b) => a.localeCompare(b, 'en'));

  for (const shortcode of shortcodes) {
    if (seen.has(shortcode)) throw new Error(`Duplicate emoji shortcode: ${shortcode}`);
    seen.add(shortcode);
  }

  if (shortcodes.length > 0) categories[categoryEntry.name] = shortcodes;
}

const serializedCategories = JSON.stringify(categories, null, 2);
const output = `/*\n * Copyright (C) 2025-2026 The 25-ji-code-de Team\n * SPDX-License-Identifier: AGPL-3.0-only\n * Generated by scripts/generate-emoji-data.mjs. Do not edit manually.\n */\n(function (global) {\n  const categories = ${serializedCategories};\n\n  for (const shortcodes of Object.values(categories)) Object.freeze(shortcodes);\n  global.NightcordEmojiData = Object.freeze({\n    baseUrl: 'https://emojis.nightcord.de5.net',\n    categories: Object.freeze(categories)\n  });\n})(window);\n`;

await writeFile(outputFile, output, 'utf8');
console.log(`Wrote ${seen.size} emoji shortcodes to ${outputFile}`);
