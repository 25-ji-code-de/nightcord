import { readFile, writeFile } from 'node:fs/promises';
import vm from 'node:vm';

const input = process.argv[2];
if (!input) {
  console.error('Usage: node scripts/generate-emoji-unicode.mjs <emoji-test.txt>');
  process.exit(1);
}

// Unicode Emoji 17.0: https://unicode.org/Public/17.0.0/emoji/emoji-test.txt
// Unicode data terms: https://www.unicode.org/license.txt
const source = await readFile(input, 'utf8');
const version = source.match(/^# Version: (.+)$/m)?.[1];
if (!version) throw new Error('Missing Unicode emoji version');
const normalize = name => name.toLowerCase().replace(/^flag: /, '')
  .replace(/^keycap: #$/, 'keycap hash').replace(/^keycap: \*$/, 'keycap asterisk')
  .replace(/[^\p{L}\p{N}]+/gu, '_').replace(/^_|_$/g, '');
const byName = new Map();
for (const line of source.split('\n')) {
  const match = line.match(/^([\dA-F ]+)\s*;\s*fully-qualified\s*#\s*\S+\s+E[\d.]+\s+(.+)$/);
  if (!match) continue;
  const unicode = String.fromCodePoint(...match[1].trim().split(/\s+/).map(hex => parseInt(hex, 16)));
  byName.set(normalize(match[2]), unicode);
}

// The hosted catalog uses a few legacy names alongside Unicode/CLDR names.
