const window = {};
vm.runInNewContext(await readFile(new URL('../emoji-data.js', import.meta.url), 'utf8'), { window });
const unicodeByShortcode = {};
const unmapped = [];
for (const [category, shortcodes] of Object.entries(window.NightcordEmojiData.categories)) {
  if (['bilibili', 'lark', 'rednote', 'tieba'].includes(category)) continue;
  for (const shortcode of shortcodes) {
    const unicode = byName.get(normalize(names[shortcode] || shortcode));
    if (unicode) unicodeByShortcode[shortcode] = unicode;
    else unmapped.push(shortcode);
  }
}
if (unmapped.length) throw new Error(`Unmapped catalog emoji: ${unmapped.join(', ')}`);

const output = `/*
 * Copyright (C) 2025-2026 The 25-ji-code-de Team
 * SPDX-License-Identifier: AGPL-3.0-only
 * Generated by scripts/generate-emoji-unicode.mjs from Unicode Emoji ${version}.
 * Unicode data terms: https://www.unicode.org/license.txt
 */
(function (global) {
  global.NightcordEmojiUnicode = Object.freeze(${JSON.stringify(unicodeByShortcode, null, 2)});
})(window);
`;
await writeFile(new URL('../emoji-unicode-data.js', import.meta.url), output, 'utf8');
console.log(`Wrote ${Object.keys(unicodeByShortcode).length} Unicode emoji mappings (${version})`);
